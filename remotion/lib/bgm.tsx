import type React from "react";
import { Audio, staticFile } from "remotion";

/** BGM tracks selectable in the RenderPanel — injected as broadcast.custom.bgm. */
export type BgmTrack = "broadcast" | "trenches" | "float";

/** Non-default track ids that map to their own file (broadcast uses bgm.mp3). */
const VARIANT_IDS = ["trenches", "float"] as const;

const srcFor = (custom?: Record<string, string>): string => {
  const id = custom?.bgm;
  return VARIANT_IDS.includes(id as (typeof VARIANT_IDS)[number])
    ? staticFile(`audio/bgm-${id}.mp3`)
    : staticFile("audio/bgm.mp3");
};

/** Float is the airy cut and sits lower in the mix; everything else 0.32. */
const volumeFor = (custom?: Record<string, string>): number =>
  custom?.bgm === "float" ? 0.26 : 0.32;

/**
 * Broadcast BGM — three 20s seamless loops (A minor: broadcast 96 BPM,
 * trenches 126 BPM, float 84 BPM), generated by scripts/make-bgm.py
 * (zero third-party rights). Every composition mounts this so exported
 * MP4s are never silent. `custom.bgm` selects the track and works both for
 * the server render (inputProps carry custom.bgm) and for dashboard/landing
 * Players (inputProps = BroadcastData).
 */
export const Bgm: React.FC<{ volume?: number; custom?: Record<string, string> }> = ({
  volume,
  custom,
}) => <Audio src={srcFor(custom)} loop volume={volume ?? volumeFor(custom)} />;

/**
 * HOC: mounts <Bgm/> alongside the composition. Used in three places:
 *  - remotion/Root.tsx          → server-side render path (the exported MP4)
 *  - dashboard composition map  → program-monitor preview
 *  - landing Players            → summon film + template previews
 * Wrap at MODULE level only — wrapping inside render creates a new component
 * type every keystroke and remounts the Player.
 */
export function withBgm<P extends object>(Comp: React.ComponentType<P>): React.ComponentType<P> {
  const Wrapped: React.FC<P> = (props) => {
    // P is generic — read custom defensively so this works for BroadcastData
    // and any other prop shape a Player passes through.
    const custom = (props as unknown as { custom?: Record<string, string> }).custom;
    return (
      <>
        <Bgm custom={custom} />
        <Comp {...props} />
      </>
    );
  };
  Wrapped.displayName = `withBgm(${Comp.displayName || Comp.name || "Comp"})`;
  return Wrapped;
}
